def _lerp(a, b, t):
    return (int(a[0]+(b[0]-a[0])*t), int(a[1]+(b[1]-a[1])*t))


def _lerp_list(la, lb, t):
    return [_lerp(a, b, t) for a, b in zip(la, lb)]


def _interp_pose(p1, p2, t):
    return dict(
        head=_lerp(p1["head"],p2["head"],t), neck=_lerp(p1["neck"],p2["neck"],t),
        ls=_lerp(p1["ls"],p2["ls"],t), rs=_lerp(p1["rs"],p2["rs"],t),
        le=_lerp(p1["le"],p2["le"],t), re=_lerp(p1["re"],p2["re"],t),
        lw=_lerp(p1["lw"],p2["lw"],t), rw=_lerp(p1["rw"],p2["rw"],t),
        lf=_lerp_list(p1["lf"],p2["lf"],t), rf=_lerp_list(p1["rf"],p2["rf"],t),
    )


def _draw_pil(pose, label, w=W, h=H):
    img = Image.new("RGB", (w, h), BG)
    d = ImageDraw.Draw(img)

    head, neck = pose["head"], pose["neck"]
    ls, rs = pose["ls"], pose["rs"]
    le, re = pose["le"], pose["re"]
    lw, rw = pose["lw"], pose["rw"]
    lf, rf = pose["lf"], pose["rf"]

    r = int(min(w,h)*0.085)
    mid_torso = ((ls[0]+rs[0])//2, (ls[1]+rs[1])//2+40)

    # Esqueleto
    d.line([neck, mid_torso], fill=BONE, width=2)
    d.line([ls, rs], fill=BONE, width=2)
    d.line([ls, le, lw], fill=BONE, width=2)
    d.line([rs, re, rw], fill=BONE, width=2)
    d.ellipse([head[0]-r, head[1]-r, head[0]+r, head[1]+r], outline=BONE, width=2)

    # Articulaciones
    for pt in [neck, ls, rs, le, re]:
        d.ellipse([pt[0]-4,pt[1]-4,pt[0]+4,pt[1]+4], fill=JOINT)

    # Manos
    for mw in [lw, rw]:
        d.ellipse([mw[0]-10,mw[1]-10,mw[0]+10,mw[1]+10], fill=HAND_FILL, outline=HAND_BORDER, width=2)

    # Dedos
    for tip in lf:
        d.line([lw, tip], fill=FINGER, width=2)
        d.ellipse([tip[0]-5,tip[1]-5,tip[0]+5,tip[1]+5], fill=HAND_FILL, outline=FINGER, width=1)
    for tip in rf:
        d.line([rw, tip], fill=FINGER, width=2)
        d.ellipse([tip[0]-5,tip[1]-5,tip[0]+5,tip[1]+5], fill=HAND_FILL, outline=FINGER, width=1)

    # Label
    safe = label.encode('ascii','replace').decode('ascii')
    bbox = d.textbbox((0,0), safe)
    tw = bbox[2]-bbox[0]
    d.text(((w-tw)//2, h-22), safe, fill=TEXT_C)

    return img


def render_pose(seña_key, frame_idx=0, width=300, height=380, label=""):
    global W, H
    W, H = width, height
    if seña_key not in POSES:
        return np.ones((height, width, 3), dtype=np.uint8)*245
    frames = POSES[seña_key]
    img = _draw_pil(frames[frame_idx % len(frames)], label, width, height)
    return np.array(img)


def render_gif(seña_key, width=320, height=400, fps=3):
    global W, H
    W, H = width, height
    from utils.vocabulary import VOCAB
    label = VOCAB.get(seña_key, {}).get("label", seña_key)
    if seña_key not in POSES:
        return None
    frames_pil = []
    pose_frames = POSES[seña_key]
    for i, pose in enumerate(pose_frames):
        frames_pil.append(_draw_pil(pose, label, width, height))
        nxt = pose_frames[(i+1) % len(pose_frames)]
        frames_pil.append(_draw_pil(_interp_pose(pose, nxt, 0.5), label, width, height))
    buf = io.BytesIO()
    frames_pil[0].save(buf, format="GIF", save_all=True,
                       append_images=frames_pil[1:], loop=0,
                       duration=int(1000/fps), optimize=False)
    return buf.getvalue()
